"""Rebuild data.js from library.db.

Browsers cannot read a SQLite file when index.html is opened straight from disk,
so the book content lives in data.js. After adding books, units or trivia to
library.db, run:   python build_data.py
(needs only Python 3; no extra packages)
"""
import json, sqlite3, os

here = os.path.dirname(os.path.abspath(__file__))
db = sqlite3.connect(os.path.join(here, "library.db"))
db.row_factory = sqlite3.Row

books = [dict(r) for r in db.execute("SELECT id,title,level,grade,subject,content FROM books ORDER BY title")]
units = {}
for r in db.execute("SELECT book_id,unit_number,unit_title FROM units ORDER BY book_id,unit_number"):
    units.setdefault(str(r["book_id"]), []).append({"n": r["unit_number"], "title": r["unit_title"]})

# trivia rows have a grade but no level (Standard vs Form). Work it out from the books,
# or from subjects that only exist at one level; otherwise show it at both levels.
PRIMARY_ONLY = {"religion", "arts", "life", "science"}
SECONDARY_ONLY = {"physics", "chem", "bio", "business", "cs"}
trivia = []
for r in db.execute("SELECT id,subject,grade,question,option_a,option_b,option_c,option_d,correct_option FROM trivia ORDER BY id"):
    t = dict(r)
    subject = (t["subject"] or "").strip().lower()
    levels = {b["level"] for b in books if str(b["grade"]) == str(t["grade"]) and (b["subject"] or "").lower() == subject}
    t["subject"] = subject
    t["level"] = next(iter(levels)) if len(levels) == 1 else ("STD" if subject in PRIMARY_ONLY else "Form" if subject in SECONDARY_ONLY else None)
    trivia.append(t)

data = {"books": books, "units": units, "trivia": trivia}
with open(os.path.join(here, "data.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by build_data.py from library.db - do not edit by hand */\n")
    f.write("window.IPHS_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"data.js written: {len(books)} book(s), {len(trivia)} trivia question(s)")
